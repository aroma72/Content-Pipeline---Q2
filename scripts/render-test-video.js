#!/usr/bin/env node
'use strict';
/**
 * render-test-video -- prove the renderer works, cheaply and in seconds.
 *
 *   node scripts/render-test-video.js
 *
 * WHY
 * Proving the video chain end to end cost ~$1.50 and half an hour a go, because
 * a real lesson is 16-22 beats with a written script, generated art, a paid
 * voiceover and brand bumpers. Three attempts went that way while the actual
 * question was far smaller: does this container render video at all?
 *
 * WHAT IT MAKES
 * A 5-second, silent, unbranded MP4:
 *   - two `info` beats, which the renderer draws from HTML/CSS, so NO art is
 *     generated and nothing is bought
 *   - durations written by hand, so no text-to-speech runs
 *   - compile-lesson.js only; stitch-brand.js is never called
 *
 * SILENCE, NOT ABSENCE
 * mixAudio skips an individual missing clip, but throws "no VO clips found" when
 * there are none at all -- so an audio-free render is not possible by simply
 * omitting the folder. Instead each beat gets a silent WAV of exactly its
 * duration, generated by ffmpeg in milliseconds. The result is a silent video
 * and no text-to-speech, without modifying the shared renderer.
 *
 * WHAT IT PROVES, AND WHAT IT DOES NOT
 * Proves: puppeteer, the animation kit, ffmpeg and the frame pipeline all work
 * in this environment, and produces a file you can watch.
 * Does NOT prove: script quality, art generation, voiceover, or branding. Those
 * are the parts a real lesson exercises.
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const REPO = path.resolve(__dirname, '..');
try { require(path.join(REPO, 'orchestrator/lib/env')).loadDotenv(); } catch { /* not fatal */ }

const { run } = require(path.join(REPO, 'orchestrator/lib/shell'));
const { PATHS } = require(path.join(REPO, 'orchestrator/lib/paths'));
// The repo root's ffmpeg is the known-good one on this machine.
const ffmpeg = require(path.join(REPO, 'node_modules/ffmpeg-static'));

const DIR = path.join(PATHS.explainerVideos, 'testing', 'render-smoke');
const log = (m) => process.stdout.write(`[render-test] ${m}\n`);

/** Two info cards. No `art`, so nothing is generated and nothing is paid for. */
const BEATS = `'use strict';
// Smoke test only -- not a lesson. Two info cards, no art, no voiceover.
module.exports = [
  {
    id: '01', mode: 'info',
    vo: 'This is a render test.',
    cap: 'Render test',
    info: { tpl: 'statement', data: {
      text: 'The renderer works.',
      hi: 'works',
      sub: 'Two cards, five seconds, no art and no sound.',
    } },
  },
  {
    id: '02', mode: 'info',
    vo: 'Frames, encoding and the animation kit are all working.',
    cap: 'End to end',
    info: { tpl: 'checks', data: {
      title: 'Proven in this container',
      items: ['Headless Chrome draws the frames', 'ffmpeg encodes the MP4'],
    } },
  },
];
`;

// 2.5s a card = a 5 second video. Normally measured from the voiceover; written
// by hand here precisely so no voiceover has to be generated.
const DURATIONS = { '01': 2.5, '02': 2.5 };

function copyTemplates(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  let n = 0;
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '__pycache__') continue;
    const from = path.join(src, e.name);
    const to = path.join(dest, e.name);
    if (e.isDirectory()) n += copyTemplates(from, to);
    else if (!fs.existsSync(to)) { fs.copyFileSync(from, to); n++; }
  }
  return n;
}

(async () => {
  const t0 = Date.now();
  log(`scaffolding ${path.relative(REPO, DIR)}`);
  const copied = copyTemplates(PATHS.videoTemplates, DIR);
  log(`  ${copied} template file(s)`);

  // Overwrite the template beats with the smoke-test ones, every time: a stale
  // beats.js from a previous run would render the wrong thing and still pass.
  fs.writeFileSync(path.join(DIR, 'beats.js'), BEATS);
  fs.writeFileSync(path.join(DIR, 'durations.json'), JSON.stringify(DURATIONS, null, 2));
  fs.rmSync(path.join(DIR, 'frames'), { recursive: true, force: true });
  fs.rmSync(path.join(DIR, 'out'), { recursive: true, force: true });

  // Silent voiceover, one clip per beat. mixAudio refuses to run with no clips
  // at all, so "no sound" has to mean silence rather than absence.
  const audioDir = path.join(DIR, 'audio');
  fs.mkdirSync(audioDir, { recursive: true });
  for (const [id, secs] of Object.entries(DURATIONS)) {
    const wav = path.join(audioDir, `vo_${id}.wav`);
    if (fs.existsSync(wav)) continue;
    await run(ffmpeg, ['-y', '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=mono',
      '-t', String(secs), '-c:a', 'pcm_s16le', wav], { timeoutMs: 60 * 1000 });
  }
  log(`${Object.keys(DURATIONS).length} silent clip(s) written`);

  if (!fs.existsSync(path.join(DIR, 'node_modules'))) {
    log('npm i (first run only)');
    await run('npm', ['i'], { cwd: DIR, timeoutMs: 15 * 60 * 1000 });
  }

  // A per-folder `npm i` can install ffmpeg-static with a binary for the WRONG
  // PLATFORM -- here it fetched a 23MB Linux build and named it ffmpeg.exe on
  // Windows. The file exists, so an existence check passes; running it fails
  // with EFTYPE, which surfaces much later as a spawn with pid 0 and no stderr
  // and reads like a broken ffmpeg command rather than a broken install.
  // So test that it RUNS, and if it does not, borrow the root's working copy.
  try {
    const binPath = require(require.resolve('ffmpeg-static', { paths: [DIR] }));
    const probe = spawnSync(binPath, ['-version'], { encoding: 'utf8' });
    if (probe.status !== 0) {
      const why = probe.error ? probe.error.code : `exit ${probe.status}`;
      fs.copyFileSync(ffmpeg, binPath);
      fs.chmodSync(binPath, 0o755);
      log(`the folder's ffmpeg could not run (${why}) -- replaced it with the repo root's`);
    }
  } catch (e) { log(`could not check the folder's ffmpeg: ${e.message}`); }

  log('compiling (headless Chrome -> frames -> ffmpeg)');
  await run('node', ['compile-lesson.js'], { cwd: DIR, timeoutMs: 20 * 60 * 1000 });

  const out = path.join(DIR, 'out', 'lesson.mp4');
  if (!fs.existsSync(out)) throw new Error(`compile reported success but ${out} is missing`);
  const kb = (fs.statSync(out).size / 1024).toFixed(0);
  log(`OK -- ${path.relative(REPO, out)} (${kb}KB) in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
  process.stdout.write(out + '\n');
})().catch((e) => {
  log('FAILED: ' + (e.message || e));
  process.exit(1);
});
